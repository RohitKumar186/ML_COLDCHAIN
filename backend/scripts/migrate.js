
import dotenv from "dotenv";
dotenv.config();

import pool from "../src/db/pool.js";

async function migrate() {
  const client = await pool.connect();

  try {
    await client.query("BEGIN");

    // Create the vaccine table if it does not exist.
    await client.query(`
      CREATE TABLE IF NOT EXISTS vaccines (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        product_identifier TEXT,
        min_storage_temp NUMERIC(7, 2),
        max_storage_temp NUMERIC(7, 2),
        temperature_unit VARCHAR(1) NOT NULL DEFAULT 'C',
        storage_instructions TEXT,
        source_reference TEXT,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        configuration_verified BOOLEAN NOT NULL DEFAULT FALSE,
        ctc_allowed BOOLEAN NOT NULL DEFAULT FALSE,
        ctc_conditions TEXT,
        ctc_max_duration_minutes INTEGER,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

        CONSTRAINT vaccines_temperature_unit_check
          CHECK (temperature_unit IN ('C', 'F')),

        CONSTRAINT vaccines_temperature_range_check
          CHECK (
            min_storage_temp IS NULL
            OR max_storage_temp IS NULL
            OR min_storage_temp < max_storage_temp
          ),

        CONSTRAINT vaccines_ctc_duration_check
          CHECK (
            ctc_max_duration_minutes IS NULL
            OR ctc_max_duration_minutes > 0
          )
      );
    `);

    // Add newer fields safely if the table already exists.
    await client.query(`
      ALTER TABLE vaccines
        ADD COLUMN IF NOT EXISTS product_identifier TEXT,
        ADD COLUMN IF NOT EXISTS min_storage_temp NUMERIC(7, 2),
        ADD COLUMN IF NOT EXISTS max_storage_temp NUMERIC(7, 2),
        ADD COLUMN IF NOT EXISTS temperature_unit VARCHAR(1) DEFAULT 'C',
        ADD COLUMN IF NOT EXISTS storage_instructions TEXT,
        ADD COLUMN IF NOT EXISTS source_reference TEXT,
        ADD COLUMN IF NOT EXISTS is_active BOOLEAN DEFAULT TRUE,
        ADD COLUMN IF NOT EXISTS configuration_verified BOOLEAN DEFAULT FALSE,
        ADD COLUMN IF NOT EXISTS ctc_allowed BOOLEAN DEFAULT FALSE,
        ADD COLUMN IF NOT EXISTS ctc_conditions TEXT,
        ADD COLUMN IF NOT EXISTS ctc_max_duration_minutes INTEGER,
        ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT NOW(),
        ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_vaccines_active_name
      ON vaccines (is_active, name);
    `);

    await client.query("COMMIT");

    console.log("Vaccine database migration completed successfully.");
  } catch (error) {
    await client.query("ROLLBACK");

    console.error(
      "Vaccine database migration failed:",
      error.message
    );

    throw error;
  } finally {
    client.release();
    await pool.end();
  }
}

migrate().catch(() => {
  process.exitCode = 1;
});
